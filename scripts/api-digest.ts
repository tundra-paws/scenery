// scripts/api-digest.ts
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'

/**
 * What the scene library offers, and which part of it this world uses.
 *
 *   bun run api:digest            write .scenery/api.md and say how big it is
 *   bun run api:digest --print    also print it
 *
 * A run starts with no memory, and without this each one rebuilds what it could
 * not see was already there. The digest is generated from the installed
 * package's own type declarations, so it is exact for the version in the
 * lockfile and cannot drift from it. Grep it before writing a helper, and never
 * guess a signature.
 *
 * The parse is a regex over the shipped `.d.ts` files rather than a trip through
 * the typescript compiler. These tools have to keep working when the dependency
 * tree is exactly what is under suspicion, and a barrel of re-exports is not a
 * language, it is a list.
 */

const PACKAGE = 'threejs-scenes'

const ROOT    = resolve(import.meta.dir, '..')

const HOME    = join(ROOT, 'node_modules', PACKAGE)

const DIST    = join(HOME, 'dist')

const OUT     = join(ROOT, '.scenery', 'api.md')

/** The subpaths this project imports from, and the barrel each resolves to. */
const ENTRIES: Record<string, string> = {
  [PACKAGE]:                 'index.d.ts',
  [`${PACKAGE}/core`]:       'core/index.d.ts',
  [`${PACKAGE}/primitives`]: 'primitives/index.d.ts',
  [`${PACKAGE}/raster`]:     'raster/index.d.ts',
  [`${PACKAGE}/compose`]:    'compose/index.d.ts',
  [`${PACKAGE}/state`]:      'state/index.d.ts',
}

/** Things the framework forbids in this repository, however the library exports them. */
const OFF_LIMITS = /^create(?:Fps|Rails|Orbit|Tpp|Iso)Scaffold$|^bootstrapScene$|^createFrameLoop$/u

/** Re-export chains are a tree a few levels deep; this is a guard, not a limit anyone meets. */
const MAX_DEPTH = 6

interface Declared {
  name: string

  /** `function`, `const`, `class`, `interface` or `type`. */
  kind: string

  /** The declaration's first line, trimmed: enough to call it correctly. */
  signature: string
}

type DigestReturnType = { text: string, total: number, used: number }

function read (path: string): string {
  try {
    return readFileSync(path, 'utf8')
  }
  catch {
    return ''
  }
}

/** Everything one file declares itself, by name. */
function declarationsIn (path: string): Map<string, Declared> {
  const found = new Map<string, Declared>()
  const text  = read(path)

  for (const match of text.matchAll(/^export declare (?:abstract )?(function|const|class|enum) (\w+)([^\n]*)/gmu))
    found.set(match[2]!, { name: match[2]!, kind: match[1]!, signature: `${match[2]!}${match[3]!}`.replace(/;$/u, '').slice(0, 260) })

  for (const match of text.matchAll(/^export (interface|type) (\w+)/gmu))
    found.set(match[2]!, { name: match[2]!, kind: match[1]!, signature: match[2]! })

  return found
}

/**
 * Every name a barrel puts on a subpath.
 *
 * Follows `export { a, b } from` and `export * from`. A namespace re-export
 * (`export * as core from`) is skipped: its members are listed under their own
 * subpath, which is how this project imports them.
 */
function exportsOf (path: string, depth = 0): Map<string, Declared> {
  const found = declarationsIn(path)

  if (depth > MAX_DEPTH)
    return found

  const text = read(path)
  const next = (specifier: string): string => join(dirname(path), specifier.replace(/\.js$/u, '.d.ts'))

  for (const match of text.matchAll(/^export \* from ['"](.+?)['"]/gmu))
    for (const [ name, symbol ] of exportsOf(next(match[1]!), depth + 1))
      found.set(name, symbol)

  for (const match of text.matchAll(/^export (?:type )?\{([^}]+)\} from ['"](.+?)['"]/gmu)) {
    const source = exportsOf(next(match[2]!), depth + 1)

    for (const part of match[1]!.split(',')) {
      const [ original, alias ] = part.trim().replace(/^type /u, '')
        .split(/\s+as\s+/u)
      const symbol              = source.get(original!)

      if (symbol)
        found.set(alias ?? original!, { ...symbol, name: alias ?? original! })
    }
  }

  return found
}

/** Every TypeScript source file under a directory. */
function sources (dir: string): string[] {
  if (!existsSync(dir))
    return []

  return readdirSync(dir).flatMap(name => {
    const path = join(dir, name)

    if (statSync(path).isDirectory())
      return sources(path)

    return name.endsWith('.ts') ? [ path ] : []
  })
}

function digest (): DigestReturnType {
  const version = (JSON.parse(read(join(HOME, 'package.json')) || '{}') as { version?: string }).version ?? 'not installed'
  const code    = sources(join(ROOT, 'src')).map(read)
    .join('\n')

  const lines = [
    `# ${PACKAGE} ${version}: what it exports`,
    '',
    'Generated by `bun run api:digest` from the installed type declarations. `*` marks what `src/` already uses.',
    'Functions show their real signature. For a type, read its file under `node_modules/threejs-scenes/dist/`.',
    '',
  ]

  let total = 0
  let used  = 0

  for (const [ subpath, barrel ] of Object.entries(ENTRIES)) {
    const symbols  = [ ...exportsOf(join(DIST, barrel)).values() ].sort((a, b) => a.name.localeCompare(b.name))
    const callable = symbols.filter(symbol => symbol.kind !== 'interface' && symbol.kind !== 'type')
    const types    = symbols.filter(symbol => symbol.kind === 'interface' || symbol.kind === 'type')

    lines.push(`## \`${subpath}\``, '')

    for (const symbol of callable) {
      const mark = new RegExp(String.raw `\b${symbol.name}\b`, 'u').test(code)

      total += 1
      used  += mark ? 1 : 0

      lines.push(OFF_LIMITS.test(symbol.name)
        ? `- ~~${symbol.name}~~ (not for this repository: it owns its own loop)`
        : `- ${mark ? '*' : ' '} \`${symbol.signature}\``)
    }

    if (types.length > 0)
      lines.push('', `types: ${types.map(symbol => symbol.name).join(', ')}`)

    lines.push('')
  }

  return { text: `${lines.join('\n')}\n`, total, used }
}

function main (): void {
  const { text, total, used } = digest()

  mkdirSync(dirname(OUT), { recursive: true })
  writeFileSync(OUT, text)
  console.log(`api · ${used} of ${total} exports used · .scenery/api.md (${Math.round(text.length / 1024)} KB)`)

  if (process.argv.includes('--print'))
    console.log(text)
}

main()
